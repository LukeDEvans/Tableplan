#!/usr/bin/env node
// Bundles supabase/functions/liv-mcp/tools.js (and the app's pure modules it
// imports: calendar/, views.js, assistant-queries.js, state-sync.js,
// travel-model.js) into one ES module for the Supabase Edge Function liv-mcp, so
// it deploys as plain files with no imports outside its folder. Run after changing
// any of them:
//   npm run build:liv-mcp        (writes the bundle)
//   node scripts/build-liv-mcp.mjs --check   (exit 1 when it's out of date)
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const entry = fileURLToPath(new URL("../supabase/functions/liv-mcp/tools.js", import.meta.url));
const outfile = fileURLToPath(new URL("../supabase/functions/liv-mcp/tools.bundle.js", import.meta.url));

export async function bundleLivMcp() {
  const out = await build({
    entryPoints: [entry], bundle: true, format: "esm", platform: "neutral", target: "es2022",
    write: false, legalComments: "none", logLevel: "silent",
    banner: { js: "// GENERATED by scripts/build-liv-mcp.mjs from supabase/functions/liv-mcp/tools.js — do not edit." },
  });
  return out.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundleLivMcp();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(outfile, "utf8"); } catch { /* missing */ }
    if (current !== text) { console.error("tools.bundle.js is out of date — run `npm run build:liv-mcp`."); process.exit(1); }
    console.log("tools.bundle.js is up to date.");
  } else {
    writeFileSync(outfile, text);
    console.log(`Wrote ${outfile} (${text.length} bytes).`);
  }
}
