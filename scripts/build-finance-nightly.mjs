#!/usr/bin/env node
// Bundles netlify/functions/_finance-nightly.js (and what it imports) into one ES
// module for the Supabase Edge Function finance-nightly. The Netlify helpers are
// CommonJS and reach finance-transactions.js with a dynamic import; Deno needs one
// plain ES module. Run after changing any of them:
//   npm run build:finance-nightly        (writes the bundle)
//   node scripts/build-finance-nightly.mjs --check   (exit 1 when it's out of date)
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const entry = fileURLToPath(new URL("../netlify/functions/_finance-nightly.js", import.meta.url));
const outfile = fileURLToPath(new URL("../supabase/functions/finance-nightly/nightly.bundle.js", import.meta.url));

export async function bundleFinanceNightly() {
  const out = await build({
    entryPoints: [entry], bundle: true, format: "esm", platform: "neutral", target: "es2022",
    write: false, legalComments: "none", logLevel: "silent",
    banner: { js: "// GENERATED by scripts/build-finance-nightly.mjs from netlify/functions/_finance-nightly.js — do not edit." },
  });
  return out.outputFiles[0].text;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await bundleFinanceNightly();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(outfile, "utf8"); } catch { /* missing */ }
    if (current !== text) { console.error("nightly.bundle.js is out of date — run `npm run build:finance-nightly`."); process.exit(1); }
    console.log("nightly.bundle.js is up to date.");
  } else {
    writeFileSync(outfile, text);
    console.log(`Wrote ${outfile} (${text.length} bytes).`);
  }
}
